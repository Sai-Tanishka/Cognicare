  AppLanguage _currentLanguage = supportedLanguages[0]; // English by default
  AppLanguage get currentLanguage => _currentLanguage;

  final Map<String, String> _cache = {};

  static String get baseUrl {
    if (kIsWeb) return 'http://127.0.0.1:8000';
    return defaultTargetPlatform == TargetPlatform.android
        ? 'http://10.0.2.2:8000'
        : 'http://127.0.0.1:8000';
  }

  void _prewarmForLanguage(String code) {
    if (code == 'en') return;
    final dict = _prewarmedDictionary[code];
    if (dict != null) {
      for (final entry in dict.entries) {
        _cache['${entry.key}_$code'] = entry.value;
      }
    }
  }

  /// Initialize and load saved language preference
  Future<void> init() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final savedCode = prefs.getString(_prefKey);
      if (savedCode != null) {
        final match = supportedLanguages.firstWhere(
          (l) => l.code == savedCode,
          orElse: () => supportedLanguages[0],
        );
        _currentLanguage = match;
        _prewarmForLanguage(match.code);
        notifyListeners();
      }
    } catch (_) {}
  }

  /// Change active language and persist choice immediately
  Future<void> setLanguage(AppLanguage language) async {
    if (_currentLanguage.code == language.code) return;
    _currentLanguage = language;
    _prewarmForLanguage(language.code);
    notifyListeners();

    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_prefKey, language.code);
    } catch (_) {}
  }

  /// Translate text into target language using backend translation API proxy
  Future<String> translate(
    String text, {
    String? targetLang,
    String sourceLang = 'auto',
  }) async {
    final target = targetLang ?? _currentLanguage.code;
    final trimmed = text.trim();

    if (trimmed.isEmpty) return text;
    if (target == 'en' && sourceLang == 'en') return text;

    final cacheKey = '${trimmed}_$target';
    if (_cache.containsKey(cacheKey)) {
      return _cache[cacheKey]!;
    }

    final dict = _prewarmedDictionary[target];
    if (dict != null && dict.containsKey(trimmed)) {
      final res = dict[trimmed]!;
      _cache[cacheKey] = res;
      return res;
    }

    try {
      final response = await http
          .post(
            Uri.parse('$baseUrl/api/translate/'),
            headers: {'Content-Type': 'application/json'},
            body: jsonEncode({
              'text': trimmed,
              'target_lang': target,
              'source_lang': sourceLang,
            }),
          )
          .timeout(const Duration(seconds: 8));

      if (response.statusCode == 200) {
        final data = jsonDecode(utf8.decode(response.bodyBytes)) as Map<String, dynamic>;
        final translated = data['translated_text']?.toString() ?? text;
        _cache[cacheKey] = translated;
        notifyListeners();
        return translated;
      }
    } catch (e) {
      debugPrint('TRANSLATION: API error: $e');
    }

    return text;
  }

  /// Synchronously retrieve cached translation if available, otherwise return original text
  String getCached(String text, {String? targetLang}) {
    final target = targetLang ?? _currentLanguage.code;
    if (target == 'en') return text;
    final trimmed = text.trim();
    final cacheKey = '${trimmed}_$target';
    if (_cache.containsKey(cacheKey)) {
      return _cache[cacheKey]!;
    }
    final dict = _prewarmedDictionary[target];
    if (dict != null && dict.containsKey(trimmed)) {
      final res = dict[trimmed]!;
      _cache[cacheKey] = res;
      return res;
    }
    return text;
  }

  /// Synchronously retrieve cached translation if available, otherwise return original text
  String translateSync(String text, {String? targetLang}) => getCached(text, targetLang: targetLang);

  /// Check whether a translated string is already cached in memory
  bool isCached(String text, {String? targetLang}) {
    final target = targetLang ?? _currentLanguage.code;
    if (target == 'en') return true;
    final trimmed = text.trim();
    final cacheKey = '${trimmed}_$target';
    if (_cache.containsKey(cacheKey)) return true;
    final dict = _prewarmedDictionary[target];
    if (dict != null && dict.containsKey(trimmed)) {
      _cache[cacheKey] = dict[trimmed]!;
      return true;
    }
    return false;
  }

  /// Translate a list of texts concurrently and notify listeners once finished
  Future<List<String>> translateList(
    List<String> texts, {
    String? targetLang,
    String sourceLang = 'auto',
  }) async {
    final results = await Future.wait(
      texts.map((t) => translate(t, targetLang: targetLang, sourceLang: sourceLang)),
    );
    notifyListeners();
    return results;
  }

